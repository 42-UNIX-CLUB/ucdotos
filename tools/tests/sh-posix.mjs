// POSIX shell conformance cases (tools/tests/sh-posix.cases).
//
//   node tools/tests/sh-posix.mjs --build=build-NAME [--chunk=60] [--only=FROM-TO]
//       runs rootfs/usr/share/tests/sh-posix.sh inside UC.OS (tools/run.mjs), in chunks
//       so that no single boot runs long; prints every failure and a total; exits 1 if
//       any case failed or a chunk did not finish.
//   node tools/tests/sh-posix.mjs --gen [--shell=sh]
//       runs every case with a reference shell on the host and writes the expected
//       output and status of each into rootfs/usr/share/tests/sh-posix.sh.
//   node tools/tests/sh-posix.mjs --host [--shell=sh]
//       runs the generated script with a host shell (checks the runner itself).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const root = new URL('../..', import.meta.url).pathname;
const args = process.argv.slice(2);
const opt = (n, d) => { const a = args.find((x) => x.startsWith(`--${n}=`)); return a ? a.slice(n.length + 3) : d; };
const CASES = root + 'tools/tests/sh-posix.cases';
const OUT = root + 'rootfs/usr/share/tests/sh-posix.sh';

function parseCases() {
  const lines = fs.readFileSync(CASES, 'utf8').split('\n');
  const cases = [];
  let cur = null;
  for (const l of lines) {
    if (l.startsWith('@ ')) { cur = { name: l.slice(2).trim(), body: [], out: null, status: null, why: null }; cases.push(cur); continue; }
    if (!cur) continue;
    if (l.startsWith('@out')) { cur.out = (cur.out ?? '') + l.slice(5) + '\n'; continue; }
    if (l === '@empty') { cur.out = ''; continue; }
    if (l.startsWith('@status ')) { cur.status = +l.slice(8); continue; }
    if (l.startsWith('@why ')) { cur.why = l.slice(5); continue; }
    if (cur.out !== null || cur.status !== null || cur.why !== null) continue;
    cur.body.push(l);
  }
  for (const c of cases) {
    while (c.body.length && (c.body[c.body.length - 1] === '' || c.body[c.body.length - 1].startsWith('# '))) c.body.pop();
    c.snippet = c.body.join('\n');
  }
  const seen = new Set();
  for (const c of cases) { if (seen.has(c.name)) throw new Error('duplicate case ' + c.name); seen.add(c.name); }
  return cases;
}
const sq = (s) => "'" + s.replace(/'/g, "'\\''") + "'";

if (args.includes('--gen')) {
  const shell = opt('shell', 'sh');
  const cases = parseCases();
  const scratch = fs.mkdtempSync(path.join(process.env.TMPDIR || os.tmpdir(), 'shposix-'));
  let out = `# SPDX-License-Identifier: GPL-2.0-or-later
# POSIX shell conformance cases. GENERATED by tools/tests/sh-posix.mjs --gen from
# tools/tests/sh-posix.cases: edit the cases there, then regenerate.
# Reference shell for the expected values: ${spawnSync(shell, ['-c', 'echo "$BASH_VERSION"'], { encoding: 'utf8' }).stdout.trim() ? 'bash ' + spawnSync(shell, ['-c', 'echo "$BASH_VERSION"'], { encoding: 'utf8' }).stdout.trim() + ' started as ' + shell + ' (POSIX mode)' : shell}, plus the overrides in the cases file.
# Run:  sh /usr/share/tests/sh-posix.sh [FROM [TO]]
# Each case prints "ok" or "FAIL"; the last line is the count.
from=\${1:-1}
to=\${2:-100000}
pass=0
fail=0
n=0
T=/tmp/sh-posix.$$
mkdir -p $T
cd $T || exit 1
t() { # t NAME EXPECTED SNIPPET (EXPECTED is the output, "~" and the status)
  n=$((n + 1))
  if [ $n -lt $from ] || [ $n -gt $to ]; then return 0; fi
  got=$(sh -c "$3" </dev/null 2>/dev/null; echo "~$?")
  if [ "$got" = "$2" ]; then
    pass=$((pass + 1))
    echo "ok    $n $1"
  else
    fail=$((fail + 1))
    echo "FAIL  $n $1"
    echo "      expected: [$2]"
    echo "      got:      [$got]"
  fi
}
`;
  let overridden = 0, differ = [];
  cases.forEach((c, i) => {
    const dir = path.join(scratch, String(i));
    fs.mkdirSync(dir);
    const r = spawnSync(shell, ['-c', c.snippet], { cwd: dir, encoding: 'utf8', timeout: 20000, stdio: ['ignore', 'pipe', 'ignore'],
      env: { PATH: '/usr/bin:/bin', HOME: '/home/user', USER: 'user', SHELL: '/bin/sh' } });
    let stdout = r.stdout ?? '', status = r.status ?? 128 + 9;
    const ref = stdout + '~' + status;
    if (c.out !== null || c.status !== null) {
      if (c.out !== null) stdout = c.out;
      if (c.status !== null) status = c.status;
      overridden++;
      if (stdout + '~' + status !== ref) differ.push(`${c.name}: reference gave ${JSON.stringify(ref)}`);
    }
    out += `t ${sq(c.name)} ${sq(stdout + '~' + status)} ${sq(c.snippet)}\n`;
  });
  out += 'echo "sh-posix: $((pass + fail)) cases, $pass passed, $fail failed"\ncd /\n[ $fail = 0 ]\n';
  fs.writeFileSync(OUT, out);
  console.log(`${cases.length} cases written to ${path.relative(root, OUT)}; ${overridden} with an override`);
  for (const d of differ) console.log('  override differs from the reference: ' + d);
  console.log('scratch directory (can be left): ' + scratch);
  process.exit(0);
}

if (args.includes('--host')) {
  const shell = opt('shell', 'sh');
  const scratch = fs.mkdtempSync(path.join(process.env.TMPDIR || os.tmpdir(), 'shposix-host-'));
  const r = spawnSync(shell, [OUT], { cwd: scratch, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'],
    env: { PATH: '/usr/bin:/bin', HOME: '/home/user', USER: 'user', SHELL: '/bin/sh', TMPDIR: scratch } });
  const lines = r.stdout.split('\n');
  for (let i = 0; i < lines.length; i++) if (lines[i].startsWith('FAIL')) console.log(lines.slice(i, i + 3).join('\n'));
  console.log(lines.filter((l) => l.startsWith('sh-posix:')).join('\n'));
  process.exit(r.status ? 1 : 0);
}

// run inside UC.OS
const build = opt('build', 'build');
const total = parseCases().length;
const chunk = +opt('chunk', '60');
let [from, to] = (opt('only', `1-${total}`)).split('-').map(Number);
let pass = 0, fail = 0, missing = 0;
const failures = [];
for (let a = from; a <= to; a += chunk) {
  const b = Math.min(to, a + chunk - 1);
  const t0 = Date.now();
  const r = spawnSync('node', [root + 'tools/run.mjs', `--build=${build}`, '--init=/bin/sh', `--args=/usr/share/tests/sh-posix.sh ${a} ${b}`],
    { encoding: 'utf8', timeout: 60000, maxBuffer: 1 << 26 });
  const lines = (r.stdout || '').split('\n');
  const seen = new Set();
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/^(ok|FAIL)\s+(\d+) (.*)$/);
    if (!m) continue;
    seen.add(+m[2]);
    if (m[1] === 'ok') pass++;
    else {
      fail++;
      let j = i + 1;
      while (j < lines.length && !/^(ok|FAIL)\s+\d+ |^sh-posix:/.test(lines[j])) j++;
      failures.push(lines.slice(i, j).join('\n'));
    }
  }
  const lost = b - a + 1 - seen.size;
  if (lost) { missing += lost; failures.push(`chunk ${a}-${b}: ${lost} case(s) produced no result (timeout or crash; status ${r.status}, signal ${r.signal})`); }
  console.error(`cases ${a}-${b}: ${seen.size} run in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
}
for (const f of failures) console.log(f);
console.log(`sh-posix: ${to - from + 1} cases, ${pass} passed, ${fail} failed, ${missing} without a result`);
process.exit(fail || missing ? 1 : 0);
