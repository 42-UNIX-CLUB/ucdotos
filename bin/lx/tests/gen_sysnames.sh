# Generate bin/lx/sysnames.h (system call names for traces and the call table) from
# Linux's scripts/syscall.tbl, the table every new architecture uses. riscv64 takes the
# ABIs common, 64, riscv, rlimit, memfd_secret (arch/riscv/kernel/Makefile.syscalls).
# Usage: gen_sysnames.sh syscall.tbl > bin/lx/sysnames.h
# Fetch the table with: curl -O https://raw.githubusercontent.com/torvalds/linux/master/scripts/syscall.tbl
awk 'BEGIN { print "// SPDX-License-Identifier: GPL-2.0-or-later"
             print "/* Generated by bin/lx/tests/gen_sysnames.sh from Linux scripts/syscall.tbl. riscv64 names. */"
             print "static const char *const lx_sysname_tab[] = {" }
     !/^#/ && NF >= 3 && ($2=="common"||$2=="64"||$2=="riscv"||$2=="rlimit"||$2=="memfd_secret") { printf "  [%d] = \"%s\",\n", $1, $3 }
     END { print "};" }' "$1"
