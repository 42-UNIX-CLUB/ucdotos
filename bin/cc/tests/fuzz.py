# Random integer and floating expression tests. Writes C programs whose output must
# be the same when built with clang and with our cc. Undefined behaviour is avoided:
# signed + - * go through unsigned arithmetic, divisors are never 0 or -1, shift
# counts are masked and only unsigned values are shifted left.
# usage: fuzz.py SEED COUNT > prog.c
import random
import sys

TYPES = [("signed char", 8, True), ("unsigned char", 8, False), ("short", 16, True),
         ("unsigned short", 16, False), ("int", 32, True), ("unsigned", 32, False),
         ("long", 32, True), ("unsigned long", 32, False), ("long long", 64, True),
         ("unsigned long long", 64, False)]
UNS = {8: "unsigned char", 16: "unsigned short", 32: "unsigned", 64: "unsigned long long"}

seed = int(sys.argv[1])
count = int(sys.argv[2])
rnd = random.Random(seed)


def promoted(t):
    name, bits, signed = t
    if bits < 32:
        return TYPES[4]
    return t


def common(a, b):
    a, b = promoted(a), promoted(b)
    if a[1] != b[1]:
        return a if a[1] > b[1] else b
    if not a[2]:
        return a
    return b


def const(t):
    name, bits, signed = t
    choices = [0, 1, 2, 3, 7, -1, -2, 127, 128, 255, 256, 32767, 65535, 2147483647, 4294967295]
    v = rnd.choice(choices + [rnd.randrange(-2**31, 2**31), rnd.randrange(0, 2**64)])
    if bits == 64:
        v &= 2**64 - 1
        return "%dULL" % v if not signed else "(long long)%dULL" % v
    return "(%s)%d" % (name, v & 0xffffffff if not signed else ((v + 2**31) % 2**32) - 2**31)


def expr(depth, vars_):
    if depth <= 0 or rnd.random() < 0.25:
        if rnd.random() < 0.7:
            v = rnd.choice(vars_)
            return v[0], v[1]
        t = rnd.choice(TYPES)
        return const(t), t
    k = rnd.randrange(12)
    a, ta = expr(depth - 1, vars_)
    if k == 0:  # cast
        t = rnd.choice(TYPES)
        return "((%s)(%s))" % (t[0], a), t
    if k == 1:
        p = promoted(ta)
        op = rnd.choice(["-", "~"])
        if op == "-" and p[2]:
            return "((%s)(-(%s)(%s)))" % (p[0], UNS[p[1]], a), p
        return "(%s(%s))" % (op, a), p
    if k == 2:
        return "(!(%s))" % a, TYPES[4]
    b, tb = expr(depth - 1, vars_)
    t = common(ta, tb)
    if k in (3, 4, 5):  # + - * through unsigned
        op = "+-*"[k - 3]
        u = UNS[t[1]]
        return "((%s)((%s)(%s) %s (%s)(%s)))" % (t[0], u, a, op, u, b), t
    if k == 6:  # / %
        op = rnd.choice("/%")
        return "((%s)(%s) %s (%s)((%s)(%s) == 0 || (%s)(%s) == -1 ? 3 : (%s)(%s)))" % (
            t[0], a, op, t[0], t[0], b, t[0], b, t[0], b), t
    if k == 7:  # shifts
        p = promoted(ta)
        mask = p[1] - 1
        if rnd.random() < 0.5:
            u = UNS[p[1]]
            return "((%s)(%s) << ((%s) & %d))" % (u, a, b, mask), (u, p[1], False)
        return "((%s) >> ((%s) & %d))" % (a, b, mask), p
    if k == 8:
        op = rnd.choice(["&", "|", "^"])
        return "((%s) %s (%s))" % (a, op, b), t
    if k == 9:
        op = rnd.choice(["<", "<=", ">", ">=", "==", "!="])
        return "((%s) %s (%s))" % (a, op, b), TYPES[4]
    if k == 10:
        op = rnd.choice(["&&", "||"])
        return "((%s) %s (%s))" % (a, op, b), TYPES[4]
    c, tc = expr(depth - 1, vars_)
    t = common(tb, tc)
    return "((%s) ? (%s)(%s) : (%s)(%s))" % (a, t[0], b, t[0], c), t


print("// generated by fuzz.py %d %d" % (seed, count))
print("#include <stdio.h>")
vars_ = []
for i, t in enumerate(TYPES):
    for j in range(2):
        name = "v%d_%d" % (i, j)
        print("volatile %s %s = %s;" % (t[0], name, const(t)))
        vars_.append((name, t))
print("double d0 = %r, d1 = %r; float f0 = %rf;" % (rnd.uniform(-1e6, 1e6), rnd.uniform(-10, 10), round(rnd.uniform(-100, 100), 3)))
for n in range(count):
    e, t = expr(rnd.randrange(1, 6), vars_)
    print("__attribute__((noinline)) static unsigned long long e%d(void) { return (unsigned long long)(%s); }" % (n, e))
# a few floating expressions (exactly representable operations only)
fl = ["d0 + d1", "d0 * 2.0 - d1", "(double)(int)d1", "(float)d0 + f0", "d1 < f0", "(long long)(d0 / 8)",
      "(unsigned)(d1 * d1)", "-f0 * 4", "(int)(f0 > 0 ? f0 : -f0)", "d0 == d0 && d1 != f0"]
print("int main(void) {")
for n in range(count):
    print('  printf("%%d %%llx\\n", %d, e%d());' % (n, n))
for x in fl:
    print('  printf("%%.17g\\n", (double)(%s));' % x)
print("  return 0;\n}")
